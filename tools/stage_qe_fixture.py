"""Stage a real q2r/matdyn case as a QE acceptance fixture.

    python tools/stage_qe_fixture.py <source-dir> <case-name> [--every N]

``<source-dir>`` must hold ``*.fc`` (q2r output), ``matdyn.in`` and the
matdyn frequency file named by that input's ``flfrq``. The fixture is written
to ``tests/fixtures/qe/real/<case-name>/`` as

    <name>.fc              copied verbatim
    matdyn.in              copied verbatim (the oracle's own settings)
    reference_freqs.csv    GENERATED: q1,q2,q3,nu_1..nu_3N  (crystal q, THz)
    PROVENANCE.md          GENERATED: settings that condition the comparison

Derived data is generated, never typed: re-run this to refresh.

The matdyn ``.freq`` layout is read from the file, not assumed. This project's
own reference file carries FOUR numbers per q-point — the three components
plus the accumulated band-path distance that ``q_in_band_form`` adds — so the
per-q stride is derived from the token count and the declared ``nbnd``/``nks``
rather than hard-coded. A ``.freq`` written without the distance column parses
equally well.

Frequencies are converted cm^-1 -> THz with the project's frozen constant.
Negative (imaginary) entries keep their sign: the sign is physics.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil

import numpy as np

THZ_TO_CM1 = 33.35641          # the project's frozen constant (io/json_v1)


def read_matdyn_freq(path):
    """Return (q (Nq,3), freq_cm1 (Nq,Nbnd)) from a matdyn frequency file."""
    with open(path) as fh:
        text = fh.read()
    head = text.split("/", 1)
    m_b = re.search(r"nbnd\s*=\s*(\d+)", head[0])
    m_k = re.search(r"nks\s*=\s*(\d+)", head[0])
    if not (m_b and m_k):
        raise ValueError(f"{path}: no '&plot nbnd=..., nks=... /' header")
    nbnd, nks = int(m_b.group(1)), int(m_k.group(1))

    vals = np.array([float(x) for x in head[1].split()])
    stride, rem = divmod(vals.size, nks)
    if rem or stride < 3 + nbnd:
        raise ValueError(
            f"{path}: {vals.size} numbers do not divide into {nks} q-points "
            f"of >= {3 + nbnd} (got stride {stride}, remainder {rem})")
    block = vals.reshape(nks, stride)
    n_qcols = stride - nbnd            # 3, or 4 when the path distance is written
    if n_qcols not in (3, 4):
        raise ValueError(f"{path}: unexpected {n_qcols} q columns per point")
    return block[:, :3], block[:, n_qcols:]


def parse_matdyn_in(path):
    """The settings that condition any comparison against this reference."""
    txt = open(path).read()

    def grab(key, default=None):
        m = re.search(rf"{key}\s*=\s*'?([^',\s]+)'?", txt, re.I)
        return m.group(1) if m else default

    return {"asr": grab("asr", "no"),
            "flfrq": grab("flfrq"),
            "flfrc": grab("flfrc"),
            "q_in_cryst_coord": (grab("q_in_cryst_coord", ".false.")
                                 .lower().startswith(".t")),
            "q_in_band_form": (grab("q_in_band_form", ".false.")
                               .lower().startswith(".t"))}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("source", help="directory holding the q2r/matdyn outputs")
    ap.add_argument("case", help="fixture name under tests/fixtures/qe/real/")
    ap.add_argument("--every", type=int, default=10,
                    help="keep every Nth q-point (default 10; the full band "
                         "path is far more than an acceptance test needs)")
    args = ap.parse_args()

    src = args.source
    fcs = sorted(f for f in os.listdir(src) if f.endswith(".fc"))
    if len(fcs) != 1:
        raise SystemExit(f"{src}: expected exactly one .fc, found {fcs}")
    mdin = os.path.join(src, "matdyn.in")
    if not os.path.exists(mdin):
        raise SystemExit(f"{src}: no matdyn.in")
    cfg = parse_matdyn_in(mdin)
    freq_path = os.path.join(src, cfg["flfrq"] or "")
    if not os.path.exists(freq_path):
        raise SystemExit(f"{src}: flfrq file {cfg['flfrq']!r} not found")

    q, f_cm1 = read_matdyn_freq(freq_path)
    sel = slice(None, None, max(1, args.every))
    q, f_cm1 = q[sel], f_cm1[sel]
    f_thz = np.sort(f_cm1 / THZ_TO_CM1, axis=1)

    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "tests", "fixtures", "qe", "real", args.case)
    os.makedirs(out, exist_ok=True)
    shutil.copyfile(os.path.join(src, fcs[0]), os.path.join(out, fcs[0]))
    shutil.copyfile(mdin, os.path.join(out, "matdyn.in"))

    rows = np.hstack([q, f_thz])
    header = ("q1,q2,q3," + ",".join(f"nu{i + 1}" for i in range(f_thz.shape[1]))
              + f"\n# generated by tools/stage_qe_fixture.py from {cfg['flfrq']}"
              + f"\n# q: {'CRYSTAL (primitive fractional)' if cfg['q_in_cryst_coord'] else 'CARTESIAN 2pi/alat — NOT directly usable'}"
              + f"\n# frequencies: THz (cm^-1 / {THZ_TO_CM1}), ascending, sign kept"
              + f"\n# matdyn asr = {cfg['asr']!r}")
    np.savetxt(os.path.join(out, "reference_freqs.csv"), rows,
               delimiter=",", header=header, fmt="%.10g")

    # provenance: the two settings that decide whether a direct comparison is
    # even meaningful, stated where a future reader will look
    from phonon_core.qe_import import read_qe_fc
    qe = read_qe_fc(os.path.join(out, fcs[0]))
    with open(os.path.join(out, "PROVENANCE.md"), "w") as fh:
        fh.write(f"""# QE acceptance fixture: {args.case}

Source: `{os.path.abspath(src)}`

| | |
|---|---|
| composition | {''.join(sorted(set(qe.symbols)))} ({len(qe.symbols)} atoms/cell) |
| q-grid | {qe.nr[0]}x{qe.nr[1]}x{qe.nr[2]} |
| polar (Born/dielectric present) | **{qe.polar}** |
| species resolution | {qe.symbol_sources} |
| matdyn `asr` | `{cfg['asr']}` |
| q in reference | {'crystal (primitive fractional)' if cfg['q_in_cryst_coord'] else 'CARTESIAN — needs conversion'} |
| q-points kept | {len(q)} of the full path (every {args.every}) |

## What this fixture can and cannot validate

**Can** (today): the READER — header quirks, quoted/blank species labels,
label-vs-mass resolution, ibrav lattice generation, the polar block layout
(per-atom index lines), the FC block indexing, and unit conversion. The Born
charges satisfy the charge-neutrality sum rule to machine precision, which is
an independent check that the polar block was read correctly.

**Cannot yet** (if `polar = True`): serve as a FREQUENCY oracle. matdyn
applies the non-analytic correction from the Born/dielectric data, and this
reference additionally used `asr = '{cfg['asr']}'`. `convert_qe_fc` refuses
polar files until the QE-to-phonopy NAC unit constant is pinned, so an
end-to-end frequency comparison would be measuring the missing LO-TO
splitting, not the reader. When NAC lands, this file becomes the oracle that
pins it — which is exactly what it is staged for.
""")
    print(f"staged {out}")
    print(f"  {fcs[0]}, matdyn.in, reference_freqs.csv "
          f"({len(q)} q x {f_thz.shape[1]} bands), PROVENANCE.md")
    print(f"  polar={qe.polar}  asr={cfg['asr']!r}  "
          f"q_cryst={cfg['q_in_cryst_coord']}")


if __name__ == "__main__":
    main()
